export const messages = { en, 'zh-CN': zh as typeof en }

export const i18n = createI18n({ legacy: false, locale: stored || browser, fallbackLocale: 'en', messages })

export function setLocale(value: 'en' | 'zh-CN') {
  i18n.global.locale.value = value
  localStorage.setItem('ew-locale', value)
}
